function [status_LLM, Answer_message, Answer_ID, Call_Token_Usage, LLM_Watchdog] = ...
    LLM_Interaction(status_LLM, Message, previous_ID, agent_data, ...
                    Answer_ID, LLM_API_Keys, LLM_Watchdog)
%LLM_INTERACTION Provider-independent CERBot LLM interaction dispatcher.
%
% The caller does NOT select OpenAI or Anthropic explicitly.
% The provider is inferred only from:
%
%       agent_data.model
%
% Consequently, changing the model in Test_Configurations from e.g.
% "luna" to "haiku" is sufficient to move the same CERBot workflow from
% OpenAI to Anthropic, provided LLM_agents_definition uses
% LLM_Model_Resolver.
%
% The function deliberately preserves the same return signature used by
% OpenAI_LLM_Interaction and Claude_LLM_Interaction.

    if ~isfield(agent_data, "model") || isempty(agent_data.model)
        error( ...
            "LLM_Interaction:MissingModel", ...
            "agent_data.model is required to select the LLM provider.");
    end

    [Provider, ~] = LLM_Model_Resolver(agent_data.model);

    switch Provider
        case "OpenAI"
            apiKey = getProviderKey(LLM_API_Keys, "OpenAI");

            [status_LLM, Answer_message, Answer_ID, Call_Token_Usage, LLM_Watchdog] = ...
                OpenAI_LLM_Interaction( ...
                    status_LLM, ...
                    Message, ...
                    previous_ID, ...
                    agent_data, ...
                    Answer_ID, ...
                    apiKey, ...
                    LLM_Watchdog);

        case "Anthropic"
            apiKey = getProviderKey(LLM_API_Keys, "Anthropic");

            [status_LLM, Answer_message, Answer_ID, ...
                Call_Token_Usage, LLM_Watchdog] = ...
                Claude_LLM_Interaction( ...
                    status_LLM, ...
                    Message, ...
                    previous_ID, ...
                    agent_data, ...
                    Answer_ID, ...
                    apiKey, ...
                    LLM_Watchdog);

        otherwise
            error( ...
                "LLM_Interaction:UnsupportedProvider", ...
                "Unsupported LLM provider: %s", ...
                Provider);
    end
end


function apiKey = getProviderKey(LLM_API_Keys, Provider)
%GETPROVIDERKEY Return only the credential required by the selected provider.

    if ~isstruct(LLM_API_Keys) || ~isfield(LLM_API_Keys, Provider)
        error( ...
            "LLM_Interaction:MissingAPIKeyField", ...
            "LLM_API_Keys.%s is not defined.", ...
            Provider);
    end

    apiKey = string(LLM_API_Keys.(Provider));

    if strlength(apiKey) == 0
        switch Provider
            case "OpenAI"
                Env_Name = "OPENAI_API_KEY";
            case "Anthropic"
                Env_Name = "ANTHROPIC_API_KEY";
            otherwise
                Env_Name = "provider API key";
        end

        error( ...
            "LLM_Interaction:MissingAPIKey", ...
            "No API key is available for %s. Set %s before running the test.", ...
            Provider, Env_Name);
    end

    apiKey = char(apiKey);
end
